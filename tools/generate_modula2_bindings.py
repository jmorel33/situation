def render_enum(e_name: str, members: list[tuple[str, str | None]], define_map: dict[str, str]) -> str:
    member_values: dict[str, int] = {}
    for name, value in members:
        if value is None:
            continue
        try:
            resolved = resolve_enum_value(value, define_map)
            expr = resolved
            for mname, mval in member_values.items():
                expr = re.sub(r"\b" + re.escape(mname) + r"\b", str(mval), expr)
            member_values[name] = eval(expr)  # noqa: S307 — controlled input
        except Exception:
            pass

    lines = [f"  {e_name} = INTEGER;"]
    const_lines: list[str] = []
    for name, value in members:
        if value is None:
            continue
        resolved = resolve_enum_value(value, define_map)
        expanded = resolved
        for mname, mval in member_values.items():
            expanded = re.sub(r"\b" + re.escape(mname) + r"\b", str(mval), expanded)
        try:
            numeric = eval(expanded)  # noqa: S307 — controlled input
            const_lines.append(f"  {name} = {numeric};")
        except Exception:
            const_lines.append(f"  {name} = {expanded};")

    if not const_lines:
        return f"  {e_name} = INTEGER;\n"

    return "\n".join(lines) + "\n\nCONST\n" + "\n".join(const_lines) + "\n"


def render_enums() -> str:
    define_map = build_define_map()
    type_parts: list[str] = []
    const_parts: list[str] = []

    errno = parse_errno_enum()
    type_parts.append(f"  {errno.name} = INTEGER;")
    for name, value in errno.members:
        if value is None:
            continue
        resolved = resolve_enum_value(value, define_map)
        const_parts.append(f"  {name} = {resolved};")

    for e in parse_enums():
        if e.name == "SituationError":
            continue
        if len(e.members) < 2:
            continue
        type_parts.append(f"  {e.name} = INTEGER;")
        member_values: dict[str, int] = {}
        for name, value in e.members:
            if value is None:
                continue
            try:
                resolved = resolve_enum_value(value, define_map)
                expr = resolved
                for mname, mval in member_values.items():
                    expr = re.sub(r"\b" + re.escape(mname) + r"\b", str(mval), expr)
                member_values[name] = eval(expr)  # noqa: S307 — controlled input
            except Exception:
                pass
        for name, value in e.members:
            if value is None:
                continue
            resolved = resolve_enum_value(value, define_map)
            expanded = resolved
            for mname, mval in member_values.items():
                expanded = re.sub(r"\b" + re.escape(mname) + r"\b", str(mval), expanded)
            try:
                numeric = eval(expanded)  # noqa: S307 — controlled input
                const_parts.append(f"  {name} = {numeric};")
            except Exception:
                const_parts.append(f"  {name} = {expanded};")

    lines = ["TYPE", "\n".join(type_parts)]
    if const_parts:
        lines.extend(["", "CONST", "\n".join(const_parts)])
    return "\n".join(lines) + "\n"


def wrap_def_module(
    name: str,
    body: str,
    imports: list[str] | None = None,
    *,
    for_linkage: str | None = None,
) -> str:
    if for_linkage:
        lines = [f'DEFINITION MODULE FOR "{for_linkage}" {name};', ""]
    else:
        lines = [f"DEFINITION MODULE {name};", ""]
    if imports:
        for imp in imports:
            lines.append(imp)
        lines.append("")
    lines.append(body.rstrip())
    lines.append("")
    lines.append(f"END {name}.")
    return "\n".join(lines) + "\n"


