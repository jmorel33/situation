def render_types(entries: list[ApiEntry]) -> str:
    pointer_aliases = collect_pointer_aliases(entries)
    body = (
        render_manual_types()
        + "\n"
        + render_pointer_aliases(pointer_aliases)
        + render_enums()
        + render_opaque_stubs(entries, pointer_aliases)
    )
    imports = ["FROM SYSTEM IMPORT ADDRESS, CARDINAL8, INTEGER16;"]
    return wrap_def_module("SituationTypes", body, imports)


def render_manual_md(entries: list[ApiEntry]) -> str:
    manual = [e for e in entries if e.manual_only or e.name in MANUAL_FUNCTIONS]
    lines = [
        "# Situation Modula-2 — Manual bindings",
        "",
        "These symbols are **not** emitted in `SituationForeign.def`. Add hand-written Modula-2 wrappers as needed.",
        "",
        "| Function | Reason |",
        "|----------|--------|",
    ]
    for e in sorted(manual, key=lambda x: x.name):
        reason = e.manual_reason or "listed in MANUAL_FUNCTIONS"
        lines.append(f"| `{e.name}` | {reason} |")
    lines.append("")
    return "\n".join(lines)


def render_api_index(entries: list[ApiEntry], version: str) -> str:
    lines = [
        "# Situation Modula-2 bindings — API index",
        "",
        f"_Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} from `sit/situation_api.h` — Situation **{version}**._",
        "",
        f"**Foreign imports:** {len(foreign_entries(entries))}",
        "",
        "| Function | Section | Modula-2 | Notes |",
        "|----------|---------|----------|-------|",
    ]
    for e in sorted(entries, key=lambda x: x.name):
        if e.manual_only or e.name in MANUAL_FUNCTIONS:
            m2 = "manual"
            note = e.manual_reason or "manual wrapper"
        else:
            m2 = "auto"
            note = e.comment[:80] + ("..." if len(e.comment) > 80 else "")
        lines.append(f"| `{e.name}` | {e.section} | {m2} | {note or '—'} |")
    lines.append("")
    return "\n".join(lines)


def collect_referenced_types(entries: list[ApiEntry]) -> set[str]:
    referenced: set[str] = set()
    type_pattern = re.compile(r"\b([A-Z][A-Za-z0-9_]*)\b")
    for e in foreign_entries(entries):
        parsed = parse_function_signature(e.signature, c_type_to_m2)
        if not parsed:
            continue
        ret, _name, params = parsed
        if ret != VOID_RETURN:
            for m in type_pattern.finditer(ret):
                referenced.add(m.group(1))
        for _pname, ptype in params:
            for m in type_pattern.finditer(ptype):
                referenced.add(m.group(1))
    return referenced


def render_opaque_stubs(entries: list[ApiEntry], pointer_aliases: dict[str, str] | None = None) -> str:
    referenced = collect_referenced_types(entries)
    known_types = {
        "BOOLEAN", "CHAR", "INTEGER", "CARDINAL", "LONGINT", "LONGCARD",
        "REAL", "LONGREAL", "ADDRESS", "CARDINAL8", "INTEGER8",
        "CARDINAL16", "INTEGER16",
        "ColorRGBA", "SitRectangle", "Vector2", "Vector3", "Vector4",
        "SituationTexture", "SituationShader", "SituationMesh", "SituationFont", "SituationPackedFont",
        "SituationCommandBuffer", "SituationThreadPool",
        "SituationAudioGraph", "SituationNode",
        "SituationJobId", "SituationNodeHandle",
        "SituationModifiers", "SituationStreamSize", "SituationStreamResult",
        "SituationSeekOrigin", "FILE",
        "SituationSound", "SituationBuffer", "SituationComputePipeline",
        "SituationCameraDesc", "SituationRenderPassInfo",
        "SituationTextureBlitRegion",
        "SituationInitInfo", "SituationError",
        "SituationThreadPoolOpaque", "SituationAudioGraphOpaque", "SituationNodeOpaque",
        "SituationCameraDescOpaque", "SituationRenderPassInfoOpaque",
        "ma_int64", "ma_seek_origin", "Mat4", "mat4",
        "SituationLogLevel", "SituationInitState",
    }
    for e in parse_enums():
        known_types.add(e.name)
    errno = parse_errno_enum()
    known_types.add(errno.name)
    if pointer_aliases:
        known_types.update(pointer_aliases.keys())
        known_types.update(pointer_aliases.values())

    api_text = (ROOT / "sit" / "situation_api.h").read_text(encoding="utf-8", errors="replace")
    base_text = (ROOT / "sit" / "situation_base_callbacks.h").read_text(encoding="utf-8", errors="replace")
    for cb in parse_callbacks(api_text + "\n" + base_text):
        name = cb.name if cb.name.endswith("Callback") else cb.name + "Callback"
        known_types.add(name)

    missing = sorted(referenced - known_types)
    if not missing:
        return ""

    lines = [
        "",
        "(* --- Auto-generated opaque type stubs --- *)",
        "(* These types are referenced by the API but their layout is internal. *)",
        "(* Pass them by pointer. If you need field access, define them manually. *)",
        "",
        "TYPE",
    ]
    for t in missing:
        if len(t) <= 2 or t in ("Select", "First", "String", "POINTER", "TO"):
            continue
        lines.append(f"  {t} = POINTER TO {t}Opaque;")
        lines.append(f"  {t}Opaque = RECORD END;")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate GNU Modula-2 FFI bindings for Situation")
    parser.add_argument(
        "--lib",
        default="situation_opengl",
        help="Library name for linking (without .lib extension)",
    )
    args = parser.parse_args()
    _ = args.lib  # Reserved for future build script integration.

    version = read_version()
    entries = parse_api_header()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_ROOT.mkdir(parents=True, exist_ok=True)

    banner = gen_m2_banner(version)

    written: list[Path] = []
    files = {
        OUT_DIR / "SituationTypes.def": banner + render_types(entries),
        OUT_DIR / "SituationCallbacks.def": banner + render_callbacks(),
        OUT_DIR / "SituationForeign.def": banner + render_foreign(entries),
        OUT_DIR / "SituationConstants.def": banner + render_constants(),
        OUT_DIR / "SituationHelpers.def": banner + render_helpers_def(),
        OUT_DIR / "SituationHelpers.mod": banner + render_helpers_mod(),
        OUT_ROOT / "API_INDEX.md": render_api_index(entries, version),
        OUT_ROOT / "MANUAL_BINDINGS.md": render_manual_md(entries),
    }

    errors: list[str] = []
    for path, content in files.items():
        try:
            path.write_text(content, encoding="utf-8")
            written.append(path)
        except OSError as exc:
            errors.append(f"{path}: {exc}")

    auto = len(foreign_entries(entries))
    print(f"Situation {version}")
    print(f"Modula-2 bindings: {auto} EXTERN procedures, {len(entries)} total SITAPI")
    for path in written:
        rel = path.relative_to(ROOT)
        print(f"Wrote {rel}")
    print(f"Files written: {len(written)}")
    if errors:
        print("Errors:")
        for err in errors:
            print(f"  {err}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()