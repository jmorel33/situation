def m2_scalar_base(ctype: str) -> str:
    """Map a C scalar/struct name to a Modula-2 type (no pointer suffix)."""
    ctype = normalize_c_type(ctype)
    if "(*" in ctype or ctype.endswith("Callback"):
        base = ctype.split("(")[0].strip().replace("*", "").strip()
        if not base.endswith("Callback"):
            base += "Callback"
        return base

    base = ctype.replace("*", "").strip()

    if base == "void":
        return VOID_RETURN

    if base == "char":
        return "CHAR"

    if base in CTYPE_MAP:
        return CTYPE_MAP[base]
    if base.startswith("Situation") or base in (
        "ColorRGBA", "Vector2", "Vector3", "Vector4", "SitRectangle", "Mat4",
    ):
        return base
    return base if base else "ADDRESS"


def pointer_alias_name(base: str) -> str:
    """Named pointer alias required for -fpim procedure formals."""
    if base in ALREADY_POINTER_TYPES:
        return base
    return f"{base}Ptr"


def c_type_to_m2(ctype: str) -> str:
    ctype = normalize_c_type(ctype)

    if "(*" in ctype or ctype.endswith("Callback"):
        return m2_scalar_base(ctype)

    ptr_depth = ctype.count("*")
    base_raw = ctype.replace("*", "").strip()

    if base_raw == "void":
        return VOID_RETURN if ptr_depth == 0 else "ADDRESS"
    if base_raw == "char":
        return "CHAR" if ptr_depth == 0 else "ADDRESS"

    base = m2_scalar_base(ctype)
    if ptr_depth == 0:
        return base
    if ptr_depth == 1:
        return pointer_alias_name(base)
    inner = pointer_alias_name(base)
    for _ in range(ptr_depth - 2):
        inner = pointer_alias_name(inner)
    return inner


def consider_pointer_alias(ctype: str, aliases: dict[str, str]) -> None:
    norm = normalize_c_type(ctype)
    if "(*" in norm or norm.endswith("Callback"):
        return
    ptr_depth = norm.count("*")
    if ptr_depth == 0:
        return
    base_raw = norm.replace("*", "").strip()
    if base_raw in ("void", "char"):
        return
    base = m2_scalar_base(norm)
    alias = pointer_alias_name(base)
    if alias != base:
        aliases[alias] = base


def collect_pointer_aliases(entries: list[ApiEntry]) -> dict[str, str]:
    aliases: dict[str, str] = {}
    api_text = (ROOT / "sit" / "situation_api.h").read_text(encoding="utf-8", errors="replace")
    base_text = (ROOT / "sit" / "situation_base_callbacks.h").read_text(encoding="utf-8", errors="replace")
    for cb in parse_callbacks(api_text + "\n" + base_text):
        m = re.match(r"(.+?)\s*\(\*\s*\w+\s*\)\s*\((.*)\)", cb.signature)
        if not m:
            continue
        consider_pointer_alias(m.group(1).strip(), aliases)
        for p in split_params(m.group(2)):
            parsed = parse_param(p, lambda t: t)
            if parsed:
                consider_pointer_alias(parsed[1], aliases)
    for e in foreign_entries(entries):
        m = re.match(
            r"^(const\s+)?(.+?)\s+(\w+)\s*\((.*)\)\s*;?\s*$",
            strip_c_api_attributes(e.signature),
        )
        if not m:
            continue
        consider_pointer_alias(m.group(2).strip(), aliases)
        for p in split_params(m.group(4)):
            parsed = parse_param(p, lambda t: t)
            if parsed:
                consider_pointer_alias(parsed[1], aliases)
    return aliases


def render_pointer_aliases(aliases: dict[str, str]) -> str:
    if not aliases:
        return ""
    lines = [
        "(* Named pointer aliases (-fpim forbids POINTER TO in procedure formals) *)",
        "",
        "TYPE",
    ]
    for alias in sorted(aliases):
        lines.append(f"  {alias} = POINTER TO {aliases[alias]};")
    lines.append("")
    return "\n".join(lines)

TYPE_PATTERN = re.compile(r"\b([A-Z][A-Za-z0-9_]*)\b")


def scan_types_from_m2_type(type_str: str) -> set[str]:
    referenced: set[str] = set()
    cleaned = type_str
    while "POINTER TO " in cleaned:
        cleaned = cleaned.replace("POINTER TO ", "")
    for m in TYPE_PATTERN.finditer(cleaned):
        name = m.group(1)
        if name not in PRIMITIVE_NAMES:
            referenced.add(name)
    return referenced


def format_type_imports(
    referenced: set[str],
    module: str = "SituationTypes",
    *,
    include_common_extras: bool = False,
) -> list[str]:
    extras: set[str] = set()
    if include_common_extras:
        extras = {"Mat4", "ma_int64", "ma_seek_origin", "FILE"}
    names = sorted((referenced - PRIMITIVE_NAMES - {""}) | extras)
    if not names:
        return []
    return [f"FROM {module} IMPORT {', '.join(names)};"]


def render_callbacks() -> str:
    api_text = (ROOT / "sit" / "situation_api.h").read_text(encoding="utf-8", errors="replace")
    base_text = (ROOT / "sit" / "situation_base_callbacks.h").read_text(encoding="utf-8", errors="replace")
    cbs = parse_callbacks(api_text + "\n" + base_text)

    lines = [
        "(* Callback typedefs from sit/situation_api.h and sit/situation_base_callbacks.h *)",
        "",
        "TYPE",
    ]
    referenced: set[str] = set()
    seen: set[str] = set()
    for cb in cbs:
        m2_name = cb.name if cb.name.endswith("Callback") else cb.name + "Callback"
        if m2_name in seen:
            continue
        seen.add(m2_name)
        m = re.match(r"(.+?)\s*\(\*\s*\w+\s*\)\s*\((.*)\)", cb.signature)
        params: list[str] = []
        ret = VOID_RETURN
        if m:
            ret_str = m.group(1).strip()
            if ret_str != "void":
                ret = c_type_to_m2(ret_str)
                referenced |= scan_types_from_m2_type(ret)
            for p in split_params(m.group(2)):
                parsed = parse_param(p, c_type_to_m2)
                if parsed:
                    params.append(parsed[1])
                    referenced |= scan_types_from_m2_type(parsed[1])
        param_str = ", ".join(params)
        ret_suffix = m2_return_suffix(ret)
        lines.append(f"  {m2_name} = PROCEDURE ({param_str}){ret_suffix};")
        if cb.comment:
            lines.append(f"  (* {cb.comment} *)")
    body = "\n".join(lines)
    imports = ["FROM SYSTEM IMPORT ADDRESS;"]
    imports.extend(format_type_imports(referenced))
    return wrap_def_module("SituationCallbacks", body, imports)


def render_foreign(entries: list[ApiEntry]) -> str:
    NULLABLE_OVERRIDES: dict[str, str] = {
        "SituationSetActiveGraph.0": "SituationAudioGraph",
    }

    proc_names: list[str] = []
    proc_lines: list[str] = []
    type_refs: set[str] = set()
    callback_refs: set[str] = set()

    seen_names: set[str] = set()
    for e in sorted(entries, key=lambda x: x.name):
        if e.manual_only or e.name in MANUAL_FUNCTIONS:
            continue
        if e.name in seen_names:
            continue
        seen_names.add(e.name)
        parsed = parse_function_signature(e.signature, c_type_to_m2)
        if not parsed:
            proc_lines.append(f"(* SKIP (unparsed): {e.name} *)")
            continue
        ret, name, params = parsed
        proc_names.append(name)
        if ret != VOID_RETURN:
            bucket = callback_refs if ret.endswith("Callback") else type_refs
            bucket |= scan_types_from_m2_type(ret)
        param_parts = []
        for idx, (pn, pt) in enumerate(params):
            override_key = f"{name}.{idx}"
            if override_key in NULLABLE_OVERRIDES:
                pt = NULLABLE_OVERRIDES[override_key]
            param_parts.append(f"{pn}: {pt}")
            bucket = callback_refs if pt.endswith("Callback") else type_refs
            bucket |= scan_types_from_m2_type(pt)
        param_str = "; ".join(param_parts)
        ret_suffix = m2_return_suffix(ret)
        if e.comment:
            proc_lines.append(f"(* {e.comment} *)")
        proc_lines.append(f"PROCEDURE {name} ({param_str}){ret_suffix};")
        if e.comment:
            proc_lines.append("")

    export_block = "EXPORT UNQUALIFIED\n  " + ",\n  ".join(proc_names) + ";\n\n" if proc_names else ""
    body = export_block + "\n".join(proc_lines)
    imports = ["FROM SYSTEM IMPORT ADDRESS, CARDINAL8, INTEGER16;"]
    imports.extend(format_type_imports(type_refs, include_common_extras=True))
    imports.extend(format_type_imports(callback_refs, "SituationCallbacks"))
    return wrap_def_module("SituationForeign", body, imports, for_linkage="C")


def render_constants() -> str:
    names: list[str] = []
    const_lines = ["(* Selected constants from sit/situation_base_etc.h *)", "", "CONST"]
    for d in parse_defines():
        val = d.value
        if val.endswith("f"):
            val = val[:-1]
        val = re.sub(r"\s*/\*.*?\*/\s*$", "", val).strip()
        val = re.sub(r"\s*//.*$", "", val).strip()
        names.append(d.name)
        const_lines.append(f"  {d.name} = {val};")
    export_block = "EXPORT UNQUALIFIED\n  " + ",\n  ".join(names) + ";\n\n" if names else ""
    body = export_block + "\n".join(const_lines)
    return wrap_def_module("SituationConstants", body)


