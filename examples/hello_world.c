// Helper to draw a character from the bitmap font to a SituationImage
void DrawBitmapChar(SituationImage* img, unsigned char c, int cx, int cy, ColorRGBA color, float scale, float angle) {
    const unsigned char* glyph = &ibm_font_8x8[c * 8];

    // For each pixel in the 8x8 glyph
    for (int y = 0; y < 8; y++) {
        for (int x = 0; x < 8; x++) {
            if ((glyph[y] >> (7 - x)) & 1) {
                // This pixel is set. Draw a rectangle of size 'scale' at rotated position.

                // Original pixel center relative to glyph center (4,4)
                float lx = (float)x - 3.5f;
                float ly = (float)y - 3.5f;

                // Rotate
                float rad = glm_rad(angle);
                float rx = lx * cosf(rad) - ly * sinf(rad);
                float ry = lx * sinf(rad) + ly * cosf(rad);

                // Scale and translate to world
                int screen_x = cx + (int)(rx * scale * 2.0f); // 2.0 spacing factor
                int screen_y = cy + (int)(ry * scale * 2.0f);

                // Draw a block for "pixel"
                int block_size = (int)fmaxf(1.0f, scale * 2.0f);
                for(int bx=0; bx<block_size; bx++) {
                    for(int by=0; by<block_size; by++) {
                        SituationSetPixelColor(img, screen_x + bx, screen_y + by, color);
                    }
                }
            }
        }
    }
}

void DrawBitmapString(SituationImage* img, const char* str, int x, int y, ColorRGBA color, float scale, float angle) {
    int len = strlen(str);
    float rad = glm_rad(angle);
    float advance = 10.0f * scale * 2.0f; // 8 pixels + padding

    for (int i = 0; i < len; i++) {
        // Calculate position for this character along the rotated line
        int px = x + (int)(cosf(rad) * i * advance);
        int py = y + (int)(sinf(rad) * i * advance);
        DrawBitmapChar(img, (unsigned char)str[i], px, py, color, scale, angle);
    }
}

int main(int argc, char** argv) {
    SituationInitInfo config = {
        .window_title = "Situation - Hello World",
        .window_width = 800, .window_height = 600
    };
    if (SituationInit(argc, argv, &config) != SITUATION_SUCCESS) return -1;

    // 1. Create a CPU Image to draw on
    SituationImage screen_buffer = {0};
    SituationCreateImage(800, 600, 4, &screen_buffer);

    // Clear to dark blue
    SituationGenImageColor(800, 600, (ColorRGBA){10, 10, 30, 255}, &screen_buffer);

    // 2. Draw "Hello World" with different params
    printf("Rendering text to texture...\n");

    // Normal
    DrawBitmapString(&screen_buffer, "Hello World", 50, 100, (ColorRGBA){255, 255, 255, 255}, 1.0f, 0.0f);

    // Scaled & Colored
    DrawBitmapString(&screen_buffer, "BIG TEXT", 50, 200, (ColorRGBA){255, 100, 100, 255}, 2.0f, 0.0f);

    // Rotated
    DrawBitmapString(&screen_buffer, "Rotated Text", 400, 300, (ColorRGBA){100, 255, 100, 255}, 1.5f, 45.0f);

    // Rotated & Scaled
    DrawBitmapString(&screen_buffer, "Spinning?", 400, 100, (ColorRGBA){100, 100, 255, 255}, 1.0f, 15.0f);

    // 3. Upload to GPU Texture
    SituationTexture text_texture;
    SituationCreateTexture(screen_buffer, false, &text_texture);

    // Free CPU memory
    SituationUnloadImage(screen_buffer);

    // 4. Main Loop
    while (!SituationWindowShouldClose()) {
        SITUATION_BEGIN_FRAME();

        if (SituationAcquireFrameCommandBuffer()) {
            SituationCommandBuffer cmd = SituationGetMainCommandBuffer();
            SituationRenderPassInfo pass = { .display_id = -1, .color_attachment = { .loadOp = SIT_LOAD_OP_DONT_CARE } }; // We draw full screen texture, no clear needed

            SituationCmdBeginRenderPass(cmd, &pass);

            // Draw the texture covering the screen
            // Source: Full texture
            Rectangle src = {0, 0, 800, 600};
            // Dest: Full screen
            Rectangle dst = {0, 0, 800, 600};

            SituationCmdDrawTexture(cmd, text_texture, src, dst, (Vector2){0,0}, 0.0f, (ColorRGBA){255,255,255,255});

            SituationCmdEndRenderPass(cmd);
            SituationEndFrame();
        }
    }

    SituationDestroyTexture(&text_texture);
    SituationShutdown();
    return 0;
}
